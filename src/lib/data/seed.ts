function hashSource(providerId: string, title: string, start: string, url: string) {
  return createHash("sha256")
    .update(`${providerId}|${title}|${start}|${url}`)
    .digest("hex")
    .slice(0, 32);
}

function training(
  id: string,
  partial: Omit<
    Training,
    | "id"
    | "slug"
    | "source_hash"
    | "created_at"
    | "last_updated_at"
    | "status"
    | "country_code"
    | "currency"
  > & {
    currency?: string;
    status?: Training["status"];
  }
): Training {
  const slugBase = partial.title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "")
    .slice(0, 60);
  return {
    id,
    slug: `${slugBase}-${partial.start_date}`,
    currency: partial.currency ?? "PKR",
    status: partial.status ?? "upcoming",
    country_code: "PK",
    source_hash: hashSource(
      partial.provider_id,
      partial.title,
      partial.start_date,
      partial.registration_url
    ),
    created_at: now,
    last_updated_at: now,
    ...partial,
  };
}

